function submissionId(sampleCount: number) {
  const date = new Date();
  const part = (value: number) => String(value).padStart(2, "0");
  const stamp = `${date.getFullYear()}${part(date.getMonth() + 1)}${part(date.getDate())}-${part(date.getHours())}${part(date.getMinutes())}${part(date.getSeconds())}`;
  const bytes = new Uint8Array(3);
  crypto.getRandomValues(bytes);
  const token = Array.from(bytes, (value) => value.toString(16).padStart(2, "0")).join("");
  return `${stamp}_${sampleCount}样本_${token}`;
}

function prettyStatus(status: string | null | undefined, locale: Locale) {
  const map: Record<Locale, Record<string, string>> = {
    en: {
      auto_accepted: "Supported",
      accepted: "Supported",
      review_required: "Manual review",
      ambiguous: "Manual review",
      insufficient_support: "Insufficient support",
      pending_phylogeny: "Pending joint tree",
    },
    zh: {
      auto_accepted: "支持分型",
      accepted: "支持分型",
      review_required: "需人工复核",
      ambiguous: "需人工复核",
      insufficient_support: "支持度不足",
      pending_phylogeny: "等待联合建树",
    },
  };
  return status ? map[locale][status] || status : "—";
}

function prettyJobStatus(status: string, locale: Locale) {
  const labels: Record<Locale, Record<string, string>> = {
    en: { queued: "Queued", running: "Running", completed: "Completed", failed: "Failed", cancelled: "Cancelled" },
    zh: { queued: "排队中", running: "运行中", completed: "已完成", failed: "失败", cancelled: "已取消" },
  };
  return labels[locale][status] || status;
}

function progressMessage(job: AnalysisJob, locale: Locale, fallback: string) {
  if (locale === "zh") return job.progress?.message || fallback;
  const byStage: Record<string, string> = {
    queued: "Waiting for an analysis slot",
    prepare: "Reading chromatograms and preparing the sample sequence",
    quality: "Running trace quality control",
    assembly: "Orienting and assembling paired reads",
    mafft: "Adding samples to the locked 60-reference alignment",
    iqtree: "Running IQ-TREE phylogenetic inference",
    typing: "Assigning genotype from phylogenetic evidence",
    rendering: "Rendering the result tree and reports",
  };
  return byStage[job.progress?.stage || ""] || fallback;
}

function readableError(reason: unknown, locale: Locale) {
  const t = copy[locale];
  if (reason instanceof AnalysisApiError) {
    if (reason.status === 400 || reason.status === 413 || reason.status === 422) return t.errors.invalid;
    if (reason.status === 499) return t.errors.stopped;
    if (reason.status === 503) return t.errors.service;
    return locale === "zh" ? reason.message : t.errors.generic;
  }
  return reason instanceof Error && locale === "zh" ? reason.message : t.errors.generic;
}

