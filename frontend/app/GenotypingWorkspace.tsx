function percentLabel(value?: number | null) {
  if (value === null || value === undefined) return "—";
  return value <= 1 ? `${Math.round(value * 100)}%` : `${Math.round(value)}%`;
}

export function GenotypingWorkspace() {
  const [locale, setLocale] = useState<Locale>("en");
  const [mode, setMode] = useState<InputMode>("single");
  const [files, setFiles] = useState<File[]>([]);
  const [sampleId, setSampleId] = useState("");
  const [service, setService] = useState<ServiceState>("checking");
  const [job, setJob] = useState<AnalysisJob | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [batchStep, setBatchStep] = useState<BatchStep>(null);
  const t = copy[locale];

  const githubUrl = (
    import.meta as ImportMeta & { env?: Record<string, string | undefined> }
  ).env?.VITE_PUBLIC_GITHUB_URL;

  useEffect(() => {
    const saved = window.localStorage.getItem("orientia-tsa56-locale");
    const detected: Locale = saved === "en" || saved === "zh"
      ? saved
      : navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
    setLocale(detected);
    getServiceHealth()
      .then((health) => setService(health.compatible && health.ready ? "ready" : "unavailable"))
      .catch(() => setService("unavailable"));
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  }, [locale]);

  const batchGroups = useMemo(() => {
    const groups = new Map<string, File[]>();
    for (const file of files) {
      const id = autoSampleId(file.name) || fileStem(file.name) || "sample";
      groups.set(id, [...(groups.get(id) || []), file]);
    }
    return Array.from(groups.entries());
  }, [files]);

  const selectedLabel = mode === "batch"
    ? t.selectedFiles(files.length, batchGroups.length)
    : files[0]?.name || t.noFile;

  const setLanguage = (next: Locale) => {
    setLocale(next);
    window.localStorage.setItem("orientia-tsa56-locale", next);
    setError("");
  };

  const switchMode = (next: InputMode) => {
    if (busy) return;
    setMode(next);
    setFiles([]);
    setSampleId("");
    setError("");
    setJob(null);
    setBatchStep(null);
  };

  const onFiles = (list: FileList | null) => {
    if (!list) return;
    const selected = Array.from(list);
    if (mode === "single") setFiles(selected.slice(0, 2));
    else if (mode === "fasta") setFiles(selected.slice(0, 1));
    else setFiles(selected);
    if (mode === "single" && !sampleId && selected[0]) {
      setSampleId(autoSampleId(selected[0].name) || fileStem(selected[0].name));
    }
    setError("");
    setJob(null);
  };

  const run = async (event: FormEvent) => {
    event.preventDefault();
    setError("");
    setJob(null);
    if (service !== "ready") {
      setError(t.errors.service);
      return;
    }
    if (!files.length) {
      setError(t.errors.input);
      return;
    }
    if (mode === "single" && files.length > 2) {
      setError(t.errors.singleLimit);
      return;
    }
    if (mode === "batch" && batchGroups.some(([, group]) => group.length > 2)) {
      setError(t.errors.batchLimit);
      return;
    }

    setBusy(true);
    try {
      if (mode === "single") {
        const submitted = await submitAb1({
          sampleId: sampleId.trim() || autoSampleId(files[0].name) || "sample",
          files,
        });
        setJob(await waitForJob(submitted, setJob));
      } else if (mode === "fasta") {
        const submitted = await submitFasta(files[0]);
        setJob(await waitForJob(submitted, setJob));
      } else {
        const batchId = submissionId(batchGroups.length);
        const preparedIds: string[] = [];
        for (let index = 0; index < batchGroups.length; index += 1) {
          const [id, groupFiles] = batchGroups[index];
          setBatchStep({ phase: "prepare", index: index + 1, total: batchGroups.length, sampleId: id });
          const submitted = await submitAb1({
            sampleId: id,
            files: groupFiles,
            mode: "prepare",
            submissionId: batchId,
            submissionSampleCount: batchGroups.length,
          });
          const prepared = await waitForJob(submitted, setJob);
          preparedIds.push(prepared.job_id);
        }
        setBatchStep({ phase: "tree" });
        const submittedTree = await submitBatchTree(preparedIds, batchId);
        setJob(await waitForJob(submittedTree, setJob));
      }
    } catch (reason) {
      setError(readableError(reason, locale));
    } finally {
      setBusy(false);
      setBatchStep(null);
    }
  };

  const stop = async () => {
    if (!job || !busy) return;
    await cancelJob(job.job_id).catch(() => undefined);
    setBusy(false);
    setError(t.errors.stopped);
  };

  const batchStepText = batchStep?.phase === "prepare"
    ? t.prepareStep(batchStep.index, batchStep.total, batchStep.sampleId)
    : batchStep?.phase === "tree" ? t.treeStep : "";

  const treeFilename = job?.files.tree_svg || job?.files.display_tree_svg;
  const resultRows = job?.summary?.tree_typing_results || [];
  const rowSupports = resultRows
    .map((row) => row.support)
    .filter((value): value is number => typeof value === "number");
  const support = job?.summary?.tree_typing_support
    ?? (rowSupports.length ? Math.min(...rowSupports) : null);
  const rawStatus = job?.summary?.tree_typing_status || job?.summary?.target_status;
  const status = rawStatus === "completed" && resultRows.length
    ? (resultRows.every((row) => row.auto_accepted) ? "auto_accepted" : "review_required")
    : rawStatus;

  return (
    <main>
      <header className="site-header">
        <div className="brand">
          <img src="/favicon.svg" alt="" width="44" height="44" />
          <div>
            <h1>{t.brandTitle}</h1>
            <p>{t.brandSubtitle}</p>
          </div>
          <span className="version-badge">V1.0 · ARTICLE WORKFLOW</span>
        </div>
        <nav aria-label={t.navLabel}>
          <div className="language-toggle" role="group" aria-label="Language / 语言">
            <button type="button" className={locale === "en" ? "active" : ""} aria-pressed={locale === "en"} onClick={() => setLanguage("en")}>EN</button>
            <button type="button" className={locale === "zh" ? "active" : ""} aria-pressed={locale === "zh"} onClick={() => setLanguage("zh")}>中文</button>
          </div>
          <a href="#workflow">{t.methods}</a>
          <a href="#citation">{t.citation}</a>
          {githubUrl ? <a href={githubUrl} target="_blank" rel="noreferrer">GitHub</a> : <span title={t.githubPending}>GitHub</span>}
        </nav>
      </header>

      <section className="workflow-strip" id="workflow" aria-label={t.workflowLabel}>
        <span className="eyebrow">{t.workflowEyebrow}</span>
        <strong>{t.workflowInput}</strong>
        <i aria-hidden="true">→</i>
        <strong>{t.workflowAlignment}</strong>
        <i aria-hidden="true">→</i>
        <strong>{t.workflowTree}</strong>
        <span className={`service-chip ${service}`}>
          {t.service[service]}
        </span>
      </section>

      <div className="workspace-grid">
        <section className="input-panel" aria-labelledby="input-title">
          <div className="mode-tabs" role="tablist" aria-label={t.inputTabs}>
            {(["single", "batch", "fasta"] as InputMode[]).map((item) => (
              <button
                key={item}
                type="button"
                role="tab"
                aria-selected={mode === item}
                className={mode === item ? "active" : ""}
                onClick={() => switchMode(item)}
              >
                {t.inputs[item].title}
              </button>
            ))}
          </div>

          <form onSubmit={run}>
            <div className="panel-heading">
              <span className="eyebrow">INPUT</span>
              <h2 id="input-title">{t.inputs[mode].title}</h2>
              <p>{t.inputs[mode].hint}</p>
            </div>

            {mode === "single" && (
              <label className="field-label">
                {t.sampleId}
                <input
                  value={sampleId}
                  onChange={(event) => setSampleId(event.target.value)}
                  placeholder={t.samplePlaceholder}
                  maxLength={60}
                  disabled={busy}
                />
              </label>
            )}

            <label className="upload-zone">
              <input
                type="file"
                accept={acceptedFiles[mode]}
                multiple={mode !== "fasta"}
                onChange={(event) => onFiles(event.target.files)}
                disabled={busy}
              />
              <span className="upload-mark" aria-hidden="true">＋</span>
              <strong>{mode === "batch" ? t.chooseFiles : t.chooseFile}</strong>
              <small>{selectedLabel}</small>
            </label>

            {mode === "batch" && batchGroups.length > 0 && (
              <div className="batch-preview" aria-label={t.batchGroups}>
                {batchGroups.slice(0, 6).map(([id, group]) => (
                  <span key={id}>{id}<b>{group.length}</b></span>
                ))}
                {batchGroups.length > 6 && <span>{t.additionalSamples(batchGroups.length - 6)}</span>}
              </div>
            )}

            <button className="primary-button" type="submit" disabled={busy || files.length === 0 || service !== "ready"}>
              {busy ? t.running : t.start}
            </button>
            {busy && (
              <button className="stop-button" type="button" onClick={stop}>{t.stop}</button>
            )}
          </form>
        </section>

        <section className="result-panel" aria-labelledby="result-title">
          <div className="result-header">
            <div>
              <span className="eyebrow">RESULT</span>
              <h2 id="result-title">{t.result}</h2>
            </div>
            {job && <span className={`job-status ${job.status}`}>{prettyJobStatus(job.status, locale)}</span>}
          </div>

          <div aria-live="polite" aria-atomic="true">
            {error && <div className="error-box" role="alert">{error}</div>}
            {!job && !error && (
              <div className="empty-state">
                <img src="/favicon.svg" alt="" width="54" height="54" />
                <h3>{t.waiting}</h3>
                <p>{t.waitingHint}</p>
              </div>
            )}
            {job && (job.status === "queued" || job.status === "running") && (
              <div className="progress-state">
                <div className="progress-copy">
                  <span>{batchStepText || progressMessage(job, locale, t.analyzing)}</span>
                  <strong>{Math.round(job.progress?.percent || 0)}%</strong>
                </div>
                <div className="progress-track" aria-label={t.progressLabel}>
                  <span style={{ width: `${Math.max(2, job.progress?.percent || 0)}%` }} />
                </div>
                <p>{t.keepOpen}</p>
              </div>
            )}
            {job?.status === "completed" && job.summary && (
              <div className="completed-state">
                <div className="result-summary">
                  <div><span>{t.resultType}</span><strong>{resultRows.length ? t.sequences(resultRows.length) : (job.summary.predicted_type || t.review)}</strong></div>
                  <div><span>{t.group}</span><strong>{job.summary.predicted_group || "—"}</strong></div>
                  <div><span>UFBoot</span><strong>{percentLabel(support)}</strong></div>
                  <div><span>{t.decision}</span><strong>{prettyStatus(status, locale)}</strong></div>
                </div>

                {resultRows.length > 0 && (
                  <div className="table-wrap">
                    <table>
                      <thead><tr><th>{t.columns.sequence}</th><th>{t.columns.genotype}</th><th>{t.columns.group}</th><th>{t.columns.support}</th><th>{t.columns.status}</th></tr></thead>
                      <tbody>
                        {resultRows.map((row) => (
                          <tr key={row.sample_id}>
                            <td>{row.sample_id}</td>
                            <td>{row.predicted_new_genotype || "—"}</td>
                            <td>{row.predicted_new_group || "—"}</td>
                            <td>{percentLabel(row.support)}</td>
                            <td>{prettyStatus(row.status, locale)}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}

                {treeFilename && (
                  <figure className="tree-card">
                    <img src={resultFileUrl(job.job_id, treeFilename)} alt={t.treeAlt} />
                    <figcaption>{t.treeCaption}</figcaption>
                  </figure>
                )}

                <div className="download-row">
                  {Object.entries(job.files).map(([label, filename]) => (
                    <a key={label} href={resultFileUrl(job.job_id, filename)} download>{downloadLabel(label, locale)}</a>
                  ))}
                </div>
              </div>
            )}
          </div>
        </section>
      </div>

      <footer id="citation">
        <span>{t.researchOnly}</span>
        <span>V1.0 · 60ref · MAFFT 7.525 · IQ-TREE 3.0.1</span>
      </footer>
    </main>
  );
}
